import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { cleanState, togglePriority, summary, requestBody } from '../public/state.mjs';
const html = await readFile('public/index.html', 'utf8');
const css = await readFile('public/styles.css', 'utf8');
const config = JSON.parse(await readFile('firebase.json', 'utf8'));
assert.equal(config.hosting.site, 'thrive-golf-website');
assert.equal(config.hosting.public, 'public');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(new Set(ids).size, ids.length, 'Duplicate IDs');
assert.equal([...html.matchAll(/\bdata-screen="/g)].length, 15, 'Twelve original screens plus account, payment, welcome');
for (const match of html.matchAll(/(?:src|href)="((?:assets\/|styles|script)[^"]+)"/g)) await stat(`public/${match[1].split('?')[0]}`);
for (const match of css.matchAll(/url\('([^']+)'\)/g)) await stat(`public/${match[1]}`);
assert.deepEqual(cleanState(null), { goal: 'golf', priorities: [], training: '' });
assert.deepEqual(cleanState({goal:'invalid', priorities:['focus','focus','bad'], training:'level3'}),{goal:'golf',priorities:['focus'],training:''});
let state = togglePriority(cleanState(), 'focus', true);
state = togglePriority(state, 'calm', true);
state = togglePriority(state, 'reset', true);
state.training = 'pro';
assert.deepEqual(summary(state), {goal:'Golf Performance',priorities:'Focus, Calm, Reset & Recovery',training:'Pro'});
state = togglePriority(state, 'help', true);
assert.deepEqual(state.priorities, ['help']);
state = togglePriority(state, 'focus', true);
assert.deepEqual(state.priorities, ['focus']);
state = togglePriority(state, 'focus', false);
assert.deepEqual(state.priorities, []);
assert.equal(cleanState({goal:'personal', priorities:['calm'], training:'independent'}).goal, 'personal');
const body=requestBody({name:' Test Person ', email:'test@example.com',phone:'',interest:'personal',referral:'',message:'Question & details'}, {goal:'personal',priorities:['calm'],training:'independent'});
assert(body.includes('Interested in: Personal Life Advantage'));
assert(body.includes('Training priorities: Calm'));
assert(body.includes('Training level: Independent'));
assert(body.includes('Name: Test Person'));
assert(html.includes('Nothing is submitted automatically'));
await stat('public/checkout.css');
await stat('public/checkout.mjs');
const script = await readFile('public/script.js', 'utf8');
const routeTable = script.match(/const routeTable = (.+);/)[1];
for (const match of html.matchAll(/href="#(\/[^"]*)"/g)) assert(routeTable.includes("'" + match[1] + "':"), 'Missing route: ' + match[1]);
console.log('PASS: 15 screens; local assets; Firebase target; navigation routes; state sanitization; selection and summary flow; contact fallback.');
